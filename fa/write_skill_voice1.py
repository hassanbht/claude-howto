## 常见规范

### 正式写作

- 使用完整的句子
- 避免缩写
- 保持礼貌

### 随意写作

- 可以使用缩写
- 更口语化
- 更适合轻松氛围

### 专业写作

- 更少的情绪色彩
- 更多的细节描述
- 更适合技术受众

### 幽默写作

- 轻松自如
- 笑点潜在于细节
- 适合轻松的读者

